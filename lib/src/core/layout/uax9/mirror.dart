library;

int? bidiMirror(int codePoint) => const {
      0x28: 0x29,
      0x29: 0x28,
      0x5b: 0x5d,
      0x5d: 0x5b,
      0x7b: 0x7d,
      0x7d: 0x7b,
      0x3c: 0x3e,
      0x3e: 0x3c,
    }[codePoint];

int canonicalBracketEquiv(int codePoint) => switch (codePoint) {
      0x2329 => 0x3008,
      0x232a => 0x3009,
      _ => codePoint,
    };
